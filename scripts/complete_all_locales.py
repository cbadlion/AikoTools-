for lang_code, trans_map in custom_maps.items():
    loc_path = os.path.join(locale_dir, f'{lang_code}.ts')
    curr = parse_kv(loc_path)
    curr.update(trans_map)
    for k, v in es.items():
        if k not in curr:
            curr[k] = v
    write_locale_file(loc_path, lang_code, curr)
    print(f"Updated {lang_code}.ts (total {len(curr)} keys)")

# Now for all other remaining locale files, ensure every key in es is present!
for f in sorted(os.listdir(locale_dir)):
    if f.endswith('.ts') and f != 'index.ts':
        lang_code = f.replace('.ts', '')
        loc_path = os.path.join(locale_dir, f)
        curr = parse_kv(loc_path)
        changed = False
        for k, v in es.items():
            if k not in curr:
                # If available in en, check if there is an appropriate fallback
                curr[k] = v
                changed = True
        if changed:
            write_locale_file(loc_path, lang_code, curr)
            print(f"Filled missing keys in {f} (total {len(curr)} keys)")

